do $$
declare
    cust_ids int[];
    instr_ids int[];
    user_ids int[];
    cust_id int;
    instr_id int;
    user_id int;
    start_date_val date;      
    count_days_val int;       
    i int;
    total_orders int := 500;
begin
    select array_agg(id) into cust_ids from customer;
    select array_agg(id) into instr_ids from instrument;
    select array_agg(id) into user_ids from users;
    
    for i in 1..total_orders loop
        cust_id := cust_ids[floor(random() * array_length(cust_ids, 1) + 1)];
        instr_id := instr_ids[floor(random() * array_length(instr_ids, 1) + 1)];
        user_id := user_ids[floor(random() * array_length(user_ids, 1) + 1)];
        
        start_date_val := date '2026-01-01' + (random() * 140)::int;
        count_days_val := floor(random() * 14 + 1)::int;
        
        -- вставка заказа со статусом 'возвращено'
        insert into orders (
            id_customer, 
            id_instrument, 
            id_user, 
            start_date, 
            count_days, 
            status
        ) values (
            cust_id, 
            instr_id, 
            user_id, 
            start_date_val, 
            count_days_val, 
            'возвращено'
        );
    end loop;
    
    raise notice 'Вставлено % заказов за период с 2026-01-01 по 2026-06-01 (все возвращены и оплачены)', total_orders;
end;
$$;
